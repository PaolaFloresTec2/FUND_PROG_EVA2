public class EVA2_22_INCREMENTOS {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        int i = 1;
        
        //ACUMULADOR:
        //YO QUIERO QUE LA I SE INCREMENTE EN 1
        System.out.println("i =" + i);
        i = i + 1;//ACOMULADOR PORQUE SE INCREMENTA(ACTUALIZA EL VALOR DE i) AHORA i VALE 2
        System.out.println("i = " + i);
        i = i +1;
        System.out.println("i = " + i);
        i++;//incrementa en 1 el valor de la variable
        System.out.println("i = " + i);
        i+=2;//incrementa en 1 el valor de la variable en dos
        System.out.println("i = " + i);
        i--;
        System.out.println("i = " + i);
        i-=2;//decrementa en 2 el valor de la variable
        System.out.println("i = " + i);
        i*=2;//multiplica por 2 el valor de la variable
        System.out.println("i = " + i);
        
        
        //CONCLUSIÓN
        // ++ --> incrementa 1
        //i = i - 1;
        
        //-- --> decrementa 1
        //i = i - 1;
        
        //+- --> incrementa por un valor
        //i+=2; --> i = i + 2;
        
        //
        
    }
    
}
